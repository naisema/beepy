const unsigned char *glyph(int c)
{
    c = toupper((unsigned char)c);
    if (c < 32 || c > 90)
        c = 32;
    return FONT[c - 32];
}

int text_w(const char *s, int scale) { return (int)strlen(s) * CELL_W * scale; }

void draw_text(canvas_t *c, int x, int y, const char *s, int scale, int ink)
{
    for (; *s; s++) {
        const unsigned char *g = glyph(*s);
        for (int r = 0; r < GLYPH_H; r++)
            for (int col = 0; col < GLYPH_W; col++)
                if (g[r] & (0x10 >> col))
                    fillrect(c, x + col * scale, y + r * scale, scale, scale, ink);
        x += CELL_W * scale;
    }
}

void draw_ctext(canvas_t *c, int cx, int y, const char *s, int scale, int ink)
{
    draw_text(c, cx - text_w(s, scale) / 2, y, s, scale, ink);
}
